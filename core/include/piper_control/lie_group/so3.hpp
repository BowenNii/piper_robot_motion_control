#ifndef PIPER_CONTROL_LIE_GROUP_SO3_HPP
#define PIPER_CONTROL_LIE_GROUP_SO3_HPP

#include "piper_control/common/types.hpp"

namespace piper_control
{

// ============================================================
// SO(3) Lie Group Convention
//
// SO(3) 表示三维旋转矩阵集合：
//
//     SO(3) = { R ∈ R^(3×3) | R^T R = I, det(R) = 1 }
//
// 本模块中的旋转向量使用：
//
//     phi = theta * a
//
// 其中：
//
//     theta = ||phi|| : 旋转角度，单位 rad。
//     a               : 单位旋转轴，||a|| = 1。
//
// 对向量 p 的旋转写为：
//
//     p_a = R_ab p_b
//
// 表示 R_ab 将坐标系 b 中表达的向量转换到坐标系 a。
// ============================================================


// ============================================================
// 【SO3-01】 skew
//
// @brief
// 将三维向量转换为 3×3 反对称矩阵，也称 hat 算子。
//
// 对：
//
//     w = [ w_x ]
//         [ w_y ]
//         [ w_z ]
//
// 定义：
//
//     [w]^ = [  0   -w_z   w_y ]
//            [ w_z    0   -w_x ]
//            [-w_y   w_x    0  ]
//
// 满足叉乘关系：
//
//     [w]^ v = w × v
//
// 输入：
//     w : 3×1 三维向量。
//
// 输出：
//     3×3 反对称矩阵 [w]^ ∈ so(3)。
// ============================================================

[[nodiscard]] Mat3 skew(
    const Vec3& w);


// ============================================================
// 【SO3-02】 vee
//
// @brief
// 将 3×3 反对称矩阵转换回三维向量，也称 vee 算子。
//
// 对：
//
//     W = [  0   -w_z   w_y ]
//         [ w_z    0   -w_x ]
//         [-w_y   w_x    0  ]
//
// 有：
//
//     vee(W) = [ w_x ]
//              [ w_y ]
//              [ w_z ]
//
// 即：
//
//     vee([w]^) = w
//
// 输入：
//     W : 3×3 反对称矩阵，理论上应满足 W^T = -W。
//
// 输出：
//     3×1 向量 w。
// ============================================================

[[nodiscard]] Vec3 vee(
    const Mat3& W);


// ============================================================
// 【SO3-03】 rot_x
//
// @brief
// 构造绕 X 轴旋转 theta 的旋转矩阵。
//
// 数学定义：
//
//     R_x(theta) =
//     [ 1      0           0      ]
//     [ 0   cos(theta)  -sin(theta)]
//     [ 0   sin(theta)   cos(theta)]
//
// 输入：
//     theta : 绕 X 轴旋转角度，单位 rad。
//
// 输出：
//     3×3 SO(3) 旋转矩阵。
// ============================================================

[[nodiscard]] Mat3 rot_x(
    double theta);


// ============================================================
// 【SO3-04】 rot_y
//
// @brief
// 构造绕 Y 轴旋转 theta 的旋转矩阵。
//
// 数学定义：
//
//     R_y(theta) =
//     [ cos(theta)   0   sin(theta) ]
//     [     0        1       0       ]
//     [-sin(theta)   0   cos(theta) ]
//
// 输入：
//     theta : 绕 Y 轴旋转角度，单位 rad。
//
// 输出：
//     3×3 SO(3) 旋转矩阵。
// ============================================================

[[nodiscard]] Mat3 rot_y(
    double theta);


// ============================================================
// 【SO3-05】 rot_z
//
// @brief
// 构造绕 Z 轴旋转 theta 的旋转矩阵。
//
// 数学定义：
//
//     R_z(theta) =
//     [ cos(theta)  -sin(theta)  0 ]
//     [ sin(theta)   cos(theta)  0 ]
//     [     0             0      1 ]
//
// 输入：
//     theta : 绕 Z 轴旋转角度，单位 rad。
//
// 输出：
//     3×3 SO(3) 旋转矩阵。
// ============================================================

[[nodiscard]] Mat3 rot_z(
    double theta);


// ============================================================
// 【SO3-06】 so3_exp
//
// @brief
// 计算 so(3) 到 SO(3) 的指数映射。
//
// 输入旋转向量：
//
//     phi = theta * a
//
// 其中：
//
//     theta = ||phi||
//     a = phi / theta
//
// 指数映射定义：
//
//     R = exp([phi]^)
//
// 使用 Rodrigues 公式：
//
//     R = I
//       + sin(theta) / theta * [phi]^
//       + (1 - cos(theta)) / theta^2 * [phi]^2
//
// 当 theta → 0 时：
//
//     R ≈ I + [phi]^
//
// 实现中应使用小角度近似，避免除以接近零的 theta。
//
// 输入：
//     phi : 3×1 旋转向量，方向为旋转轴，模长为旋转角度 rad。
//
// 输出：
//     R : 3×3 SO(3) 旋转矩阵。
// ============================================================

[[nodiscard]] Mat3 so3_exp(
    const Vec3& phi);


// ============================================================
// 【SO3-07】 so3_log
//
// @brief
// 计算 SO(3) 到 so(3) 的对数映射。
//
// 对旋转矩阵 R：
//
//     phi = log(R)
//
// 且：
//
//     R = exp([phi]^)
//
// 旋转角度由迹得到：
//
//     theta = acos((trace(R) - 1) / 2)
//
// 当 theta 不接近 0 或 pi 时：
//
//     phi = theta / (2 sin(theta)) * vee(R - R^T)
//
// 当 theta → 0 时：
//
//     phi ≈ 0
//
// 注意：
//     当 theta 接近 pi 时，sin(theta) 接近 0，轴方向的计算存在
//     数值敏感性；实现中需采用专门的 pi 角处理逻辑。
//
// 输入：
//     R : 3×3 有效 SO(3) 旋转矩阵。
//
// 输出：
//     phi : 3×1 旋转向量，模长为主值旋转角，通常位于 [0, pi]。
// ============================================================

[[nodiscard]] Vec3 so3_log(
    const Mat3& R);


// ============================================================
// 【SO3-08】 rot_axis_angle
//
// @brief
// 根据单位旋转轴与旋转角度构造 SO(3) 旋转矩阵。
//
// 输入：
//
//     a     : 单位旋转轴，||a|| = 1。
//     theta : 绕 a 旋转的角度，单位 rad。
//
// 先构造旋转向量：
//
//     phi = theta * a
//
// 再使用 Rodrigues 公式：
//
//     R = exp([phi]^)
//
//       = I
//       + sin(theta)[a]^
//       + (1 - cos(theta))[a]^2
//
// 输入：
//     axis  : 3×1 单位旋转轴。
//     theta : 旋转角度，单位 rad。
//
// 输出：
//     R : 3×3 SO(3) 旋转矩阵。
//
// 注意：
//     调用方应保证 axis 已归一化；若 axis 模长接近零，
//     旋转轴没有定义。
// ============================================================

[[nodiscard]] Mat3 rot_axis_angle(
    const Vec3& axis,
    double theta);

}  // namespace piper_control

#endif  // PIPER_CONTROL_LIE_GROUP_SO3_HPP