#ifndef PIPER_CONTROL_LIE_GROUP_SE3_HPP
#define PIPER_CONTROL_LIE_GROUP_SE3_HPP

#include "piper_control/common/types.hpp"

namespace piper_control
{

// ============================================================
// SE(3) Lie Group Convention
//
// 本项目 Twist 统一使用：
//
//     xi = [ omega ]
//          [   v   ]
//
//     omega : 角速度 / 旋转向量，单位 rad/s 或 rad
//     v     : 线速度 / 平移代数分量，单位 m/s 或 m
//
// 对齐次变换：
//
//     T = [ R  p ]
//         [ 0  1 ]
//
// R 为 3×3 旋转矩阵，p 为 3×1 平移向量。
//
// 若采用坐标变换约定：
//
//     p_a = T_ab p_b
//
// 则 T_ab 表示“坐标系 b 相对于坐标系 a 的位姿”。
// ============================================================


// ============================================================
// 【SE3-01】 twist_hat
//
// @brief
// 将 6 维 Twist 向量转换为 4×4 se(3) 李代数矩阵。
// hat 算子：把 6 维旋量向量 ξ → 4×4 李代数矩阵
// 数学定义：
//
//     xi = [ omega ]
//          [   v   ]
//
//     xi^ = [ [omega]^  v ]
//           [    0      0 ]
//
// 其中：
//
//     [omega]^ = skew(omega)
//
// 满足：
//
//     xi^ ∈ se(3)
//
// 输入：
//     xi : 6×1 Twist，排列必须为 [omega; v]。
//
// 输出：
//     4×4 se(3) 矩阵 xi^。
// ============================================================

[[nodiscard]] Mat4 twist_hat(
    const Twist& xi);


// ============================================================
// 【SE3-02】 se3_from_rt
//
// @brief
// 根据旋转矩阵 R 与平移向量 p 构造 SE(3) 齐次变换矩阵。
//
// 数学定义：
//
//     T = [ R  p ]
//         [ 0  1 ]
//
// 其中：
//
//     R ∈ SO(3)
//     p ∈ R^3
//     T ∈ SE(3)
//
// 若使用坐标变换 T_ab，则：
//
//     p_a = R_ab p_b + p_ab
//
// 输入：
//     R : 3×3 SO(3) 旋转矩阵。
//     p : 3×1 平移向量。
//
// 输出：
//     4×4 SE(3) 齐次变换矩阵。
// ============================================================

[[nodiscard]] Mat4 se3_from_rt(
    const Mat3& R,
    const Vec3& p);


// ============================================================
// 【SE3-03】 se3_inverse
//
// @brief
// 计算 SE(3) 齐次变换矩阵的解析逆。
//
// 对：
//
//     T = [ R  p ]
//         [ 0  1 ]
//
// 利用旋转矩阵性质：
//
//     R^-1 = R^T
//
// 可得：
//
//     T^-1 = [ R^T  -R^T p ]
//            [  0      1   ]
//
// 若：
//
//     p_a = T_ab p_b
//
// 则：
//
//     p_b = T_ab^-1 p_a = T_ba p_a
//
// 输入：
//     T : 4×4 SE(3) 齐次变换矩阵。
//
// 输出：
//     T^-1 : 4×4 SE(3) 齐次变换矩阵的逆。
// ============================================================

[[nodiscard]] Mat4 se3_inverse(
    const Mat4& T);


// ============================================================
// 【SE3-04】 adjoint
//
// @brief
// 计算 SE(3) 齐次变换矩阵对应的 6×6 伴随矩阵。
//
// 对：
//
//     T = [ R  p ]
//         [ 0  1 ]
//
// 其伴随矩阵为：
//
//     Ad_T = [ R        0 ]
//            [ [p]^ R   R ]
//
// 其中：
//
//     [p]^ = skew(p)
//
// 若：
//
//     p_a = T_ab p_b
//
// 则同一个 Twist 在两个坐标系中的表达满足：
//
//     V_a = Ad_T_ab V_b
//
// 即：
//
//     [ omega_a ]   [ R        0 ] [ omega_b ]
//     [   v_a   ] = [ [p]^ R   R ] [   v_b   ]
//
// 输入：
//     T : 4×4 SE(3) 齐次变换矩阵。
//
// 输出：
//     6×6 伴随矩阵 Ad_T。
// ============================================================

[[nodiscard]] Mat6 adjoint(
    const Mat4& T);


// ============================================================
// 【SE3-05】 adjoint_inverse
//
// @brief
// 计算 SE(3) 伴随矩阵的逆。
//
// 数学定义：
//
//     Ad_T^-1 = Ad_(T^-1)
//
// 若：
//
//     V_a = Ad_T_ab V_b
//
// 则：
//
//     V_b = Ad_T_ab^-1 V_a
//         = Ad_T_ba V_a
//
// 输入：
//     T : 4×4 SE(3) 齐次变换矩阵。
//
// 输出：
//     6×6 伴随逆矩阵 Ad_T^-1。
// ============================================================

[[nodiscard]] Mat6 adjoint_inverse(
    const Mat4& T);


// ============================================================
// 【SE3-06】 little_ad
//
// @brief
// 计算 Twist 对应的 little adjoint 矩阵 ad_xi。
//
// 对：
//
//     xi = [ omega ]
//          [   v   ]
//
// 有：
//
//     ad_xi = [ [omega]^    0     ]
//             [   [v]^   [omega]^ ]
//
// Lie bracket 定义为：
//
//     [xi_1, xi_2] = ad_xi_1 xi_2
//
// 即：
//
//     [xi_1, xi_2]
//     = [ omega_1 × omega_2 ]
//       [ v_1 × omega_2 + omega_1 × v_2 ]
//
// 该矩阵常用于空间向量动力学、RNEA、Lie 群积分与
// Twist 的时间导数推导。
//
// 输入：
//     xi : 6×1 Twist，排列为 [omega; v]。
//
// 输出：
//     6×6 little adjoint 矩阵 ad_xi。
// ============================================================

[[nodiscard]] Mat6 little_ad(
    const Twist& xi);


// ============================================================
// 【SE3-07】 se3_exp
//
// @brief
// 计算 se(3) 到 SE(3) 的指数映射。
//
// 对：
//
//     xi = [ phi ]
//          [ rho ]
//
// 其中：
//
//     phi : 3×1 旋转向量。
//     rho : 3×1 平移李代数分量。
//     theta = ||phi||
//
// 指数映射定义：
//
//     T = exp(xi^)
//
//       = [ R  p ]
//         [ 0  1 ]
//
// 其中旋转部分为：
//
//     R = exp([phi]^)
//
// 平移部分为：
//
//     p = V(phi) rho
//
//     V(phi)
//     = I
//       + (1 - cos(theta)) / theta^2 * [phi]^
//       + (theta - sin(theta)) / theta^3 * [phi]^2
//
// 当 theta → 0 时：
//
//     V(phi) → I
//
// 因此：
//
//     T ≈ [ I  rho ]
//         [ 0   1  ]
//
// 输入：
//     xi : 6×1 se(3) 指数坐标，排列为 [phi; rho]。
//
// 输出：
//     T : 4×4 SE(3) 齐次变换矩阵。
// ============================================================

[[nodiscard]] Mat4 se3_exp(
    const Twist& xi);


// ============================================================
// 【SE3-08】 se3_log
//
// @brief
// 计算 SE(3) 到 se(3) 的对数映射。
//
// 对：
//
//     T = [ R  p ]
//         [ 0  1 ]
//
// 定义：
//
//     xi^ = log(T)
//
//     xi = [ phi ]
//          [ rho ]
//
// 其中：
//
//     phi = log(R)
//
//     rho = V(phi)^-1 p
//
//     theta = ||phi||
//
// V(phi)^-1 的解析表达为：
//
//     V^-1
//     = I
//       - 1/2 [phi]^
//       + ( 1/theta^2 - 1/(2 theta tan(theta/2)) ) [phi]^2
//
// 当 theta → 0 时：
//
//     V^-1 → I
//
// 因此小角度情况下：
//
//     phi ≈ 0
//     rho ≈ p
//
// 输入：
//     T : 4×4 SE(3) 齐次变换矩阵。
//
// 输出：
//     xi : 6×1 se(3) 对数坐标，排列为 [phi; rho]。
//
// 注意：
//     当旋转角接近 pi 时，SO(3) 对数映射存在数值敏感性；
//     调用方应保证输入 T 为有效的 SE(3) 齐次变换矩阵。
// ============================================================

[[nodiscard]] Twist se3_log(
    const Mat4& T);

}  // namespace piper_control

#endif  // PIPER_CONTROL_LIE_GROUP_SE3_HPP